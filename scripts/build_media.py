#!/usr/bin/env python3
"""Build deterministic, approved-only 360PE media discovery from canonical YAML.

Generated files are not tracked. Run before Quarto, including in Cloudflare builds.
"""
from __future__ import annotations

from datetime import date
from html import escape
from pathlib import Path
import re
import sys
import yaml

from validate_media import ROOT, PUBLIC, read_yaml, validate, valid_local_file, valid_url

GENERATED = "<!-- Generated by scripts/build_media.py; do not edit. -->"
SLUG = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*\Z")
CANONICAL = "https://360politicalecology.org/media/{slug}/"
FRONTMATTER = re.compile(r"\A---\s*\n(.*?)\n---(?:\s*\n|$)", re.S)


def articles(root):
    result = {}
    for path in sorted((root / "articles").rglob("*.qmd")):
        match = FRONTMATTER.match(path.read_text(encoding="utf-8-sig"))
        if match:
            meta = yaml.safe_load(match.group(1)) or {}
            if meta.get("content_id"):
                result[str(meta["content_id"])] = {"title": str(meta.get("title", "")), "path": path.relative_to(root), "status": str(meta.get("status", ""))}
    return result


def load_public(root):
    errors, _ = validate(root)
    if errors:
        raise ValueError("Existing media validation failed:\n" + "\n".join(errors))
    records, slugs = [], set()
    for path in sorted((root / "_data/media").glob("*.yml")):
        record = read_yaml(path)
        if record.get("status") not in PUBLIC:
            continue
        slug = record.get("slug")
        if not isinstance(slug, str) or not SLUG.fullmatch(slug) or len(slug) > 90:
            raise ValueError(f"{path.name}: invalid or missing public slug")
        if slug in slugs:
            raise ValueError(f"{path.name}: duplicate public slug {slug}")
        slugs.add(slug)
        if record.get("canonical_url") != CANONICAL.format(slug=slug):
            raise ValueError(f"{path.name}: canonical URL must match media slug")
        if not isinstance(record.get("summary"), str) or not record["summary"].strip():
            raise ValueError(f"{path.name}: published media requires summary")
        if not isinstance(record.get("published_at"), (date, str)):
            raise ValueError(f"{path.name}: missing published_at")
        if record.get("thumbnail_path") is not None:
            if not valid_local_file(root, record["thumbnail_path"]) or not isinstance(record.get("thumbnail_alt"), str) or not record["thumbnail_alt"].strip():
                raise ValueError(f"{path.name}: thumbnail requires local file and meaningful alt text")
        if record.get("status") == "corrected" and not isinstance(record.get("correction_notice"), str):
            raise ValueError(f"{path.name}: corrected media requires correction_notice")
        records.append(record)
    return sorted(records, key=lambda r: (str(r["published_at"]), r["media_id"]), reverse=True)


def label_map(root):
    return {x["id"]: x for x in read_yaml(root / "_data/topics.yml")["topics"]}


def mdlink(title, href):
    # Escape both visible text and Markdown link metacharacters.
    safe = str(title).replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]")
    return f"[{safe}]({href})"


def item(r, prefix):
    return f"- {mdlink(r['title'], prefix + 'media/' + r['slug'] + '/')} — {r['media_type'].replace('_', ' ').title()} · {r['published_at']}\n"


def detail(r, source, topics):
    title = r["title"]
    slug = r["slug"]
    meta = {"title": title, "description": r["summary"], "date": str(r["published_at"]), "toc": True, "search": True}
    body = [GENERATED, "---", yaml.safe_dump(meta, allow_unicode=True, sort_keys=False).strip(), "---", "",
            "[Media & Dialogues](../../media.qmd) · [360PE Review](../../publications.qmd)", "",
            str(r["summary"]), "", "## Watch, listen, or view", ""]
    if r.get("distribution"):
        for d in r["distribution"]:
            body.append("- " + mdlink("Open on " + d["platform"].title(), d["url"]))
    else:
        body.append("This 360PE media item is documented here. No external platform release is listed.")
    body.extend(["", "## Original research and evidence", ""])
    for id_ in r["source_content_ids"]:
        article = source[id_]
        body.append("- " + mdlink(article["title"], "../../" + article["path"].as_posix()) +
                    (" — advance online; final issue checks pending" if article["status"] == "advance_online" else ""))
    body.extend(["", mdlink("Source notes", "../../" + r["source_notes_path"]), "", "## Research topics", ""])
    for code in [r["primary_topic"]] + r.get("secondary_topics", []):
        body.append("- " + mdlink(topics[code]["label"], "../../topics/" + topics[code]["slug"] + "/"))
    if r.get("transcript_path"):
        body.extend(["", "## Transcript", "",
                     "The transcript is provided for accessibility and source review.",
                     "", mdlink("Read transcript file", "../../" + r["transcript_path"])])
    if r["status"] == "corrected":
        body.extend(["", "## Correction notice", "", str(r["correction_notice"])])
    body.extend(["", "## Editorial accountability", "",
                 "Published: " + str(r["published_at"]) + ". Media record: `" + r["media_id"] + "`.",
                 "Research-derived media is not independently peer reviewed unless explicitly stated.",
                 ""])
    return "\n".join(body)


def generate(root=ROOT):
    root = Path(root)
    records = load_public(root)
    sources = articles(root)
    topics = label_map(root)
    generated = root / "_generated_media"
    generated.mkdir(exist_ok=True)
    (generated / "articles").mkdir(exist_ok=True)
    (generated / "topics").mkdir(exist_ok=True)

    # Remove only files bearing our generator signature, never hand-authored pages.
    media_root = root / "media"
    if media_root.exists():
        for existing in sorted(media_root.glob("*/index.qmd")):
            if existing.read_text(encoding="utf-8").startswith(GENERATED):
                existing.unlink()
                if not list(existing.parent.iterdir()):
                    existing.parent.rmdir()
    for r in records:
        path = media_root / r["slug"] / "index.qmd"
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists():
            raise ValueError(f"Refusing to overwrite hand-authored media page: {path}")
        path.write_text(detail(r, sources, topics), encoding="utf-8")

    if records:
        archive = [GENERATED, "## Published media", "",
                   "Browse approved 360PE media products, each linked to original research and evidence notes.", ""]
        archive += [item(r, "") for r in records]
    else:
        archive = [GENERATED, "## Published media", "",
                   "No media products have been released yet. Explore the research links above while the archive is being developed.", ""]
    (generated / "archive.md").write_text("\n".join(archive) + "\n", encoding="utf-8")

    for id_, source in sources.items():
        related = [r for r in records if id_ in r["source_content_ids"]]
        lines = [GENERATED]
        if related:
            lines += ["## Related 360PE media", ""]
            lines += [item(r, "../../") for r in related]
        slug = source["path"].parent.name
        (generated / "articles" / (slug + ".md")).write_text("\n".join(lines) + "\n", encoding="utf-8")
    for code, topic in topics.items():
        related = [r for r in records if code in [r["primary_topic"]] + r.get("secondary_topics", [])]
        lines = [GENERATED]
        if related:
            lines += ["## Related 360PE media", ""]
            lines += [item(r, "../../") for r in related]
        (generated / "topics" / (topic["slug"] + ".md")).write_text("\n".join(lines) + "\n", encoding="utf-8")
    return len(records)


def main():
    try:
        count = generate()
    except (ValueError, OSError, yaml.YAMLError, KeyError, TypeError) as exc:
        print(f"ERROR: media discovery generation failed: {exc}", file=sys.stderr)
        return 1
    print(f"PASS: deterministic media discovery generated for {count} public record(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
